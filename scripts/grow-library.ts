// Grows the library from Poly Haven's CC0 models: every household piece
// (furniture, seating, tables, beds, lighting, shelves, appliances,
// electronics, office, decor) that the curated list does not already name.
// Downloads each at 1k, measures it, records it in assets/lock.json, and
// writes src/core/generated-assets.ts.
//
// Run: node --no-warnings scripts/grow-library.ts [--dry]

import { writeFile } from 'node:fs/promises'
import { ASSETS, FIXTURES, type AssetInfo } from '../src/core/assets.ts'
import { fetchModel, json, readLock, writeLock } from '../src/cli/assets.ts'

const HOME = new Set(['furniture', 'seating', 'table', 'bed', 'appliances', 'lighting', 'shelves', 'office', 'vases', 'wall decoration', 'potted plants', 'electronics', 'dishes', 'books', 'decorative', 'flowers', 'instrument'])
const NOT_HOME = new Set(['industrial', 'tools', 'rigged', 'ships', 'buildings', 'structures', 'nature', 'rocks', 'ground cover', 'trees', 'grass', 'food', 'containers'])
const SKIP = new Set(['circuit_board', 'metal_detector', 'digital_wrist_watch', 'signal_flashlight', 'garden_hose_wall_mounted_01', 'vintage_radio_transceiver', 'lightbulb_01', 'lightbulb_led', 'pull_chain_light_socket', 'modular_street_seating', 'clipboard', 'office_notepads', 'stationery_supplies', 'binder_notebook', 'wooden_spoon'])

type Info = { name: string; categories: string[]; tags: string[] }

// The library's own category for a Poly Haven piece.
function categoryOf(id: string, info: Info): string {
  const name = `${id} ${info.name}`.toLowerCase()
  const has = (...words: string[]) => words.some((w) => name.includes(w))
  if (has('sofa', 'couch', 'day_bed', 'day bed')) return 'sofa'
  if (has('bench', 'picnic')) return 'bench'
  if (has('bed')) return 'bed'
  if (has('chair', 'stool', 'ottoman', 'seating')) return 'chair'
  if (has('shelf', 'shelves', 'bookshelf', 'cabinet', 'commode', 'drawer', 'console')) return 'shelf'
  if (has('table', 'desk', 'nightstand', 'cart')) return 'table'
  if (has('lamp', 'chandelier', 'lantern', 'candle', 'sconce', 'light')) return 'lamp'
  if (has('tv', 'television', 'console', 'laptop', 'boombox', 'cassette', 'camera', 'projector', 'radio', 'fan')) return 'electronics'
  if (has('kettle', 'microwave', 'heater', 'register')) return 'appliance'
  if (has('picture', 'frame', 'mirror', 'clock', 'dartboard', 'chalkboard', 'screen')) return 'wall'
  if (has('pillow', 'rug', 'cushion')) return 'textile'
  return 'decor'
}

const slug = (id: string) => id.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

async function main() {
  const dry = process.argv.includes('--dry')
  const all = (await json('https://api.polyhaven.com/assets?t=models')) as Record<string, Info>
  const known = new Set([...ASSETS.map((a) => a.model).filter(Boolean), ...Object.values(FIXTURES)])
  const candidates = Object.entries(all)
    .filter(([id, info]) => !SKIP.has(id) && !known.has(id) && info.categories.some((c) => HOME.has(c)) && !info.categories.some((c) => NOT_HOME.has(c)))
    .sort(([a], [b]) => a.localeCompare(b))
  console.log(`${candidates.length} candidates`)
  if (dry) {
    for (const [id, info] of candidates) console.log(`${categoryOf(id, info)}/${slug(id)}  ${info.name}`)
    return
  }
  const lock = await readLock()
  const generated: AssetInfo[] = []
  for (const [id, info] of candidates) {
    try {
      const size = lock.models[id]?.size ?? (await fetchModel(id, '1k', lock))
      const category = categoryOf(id, info)
      const words = new Set<string>([category, ...info.categories.filter((c) => !c.startsWith('collection')), ...info.tags, ...info.name.toLowerCase().split(/\s+/)])
      generated.push({ id: `${category}/${slug(id)}`, model: id, name: info.name, category, size, tags: [...words].filter((w) => /^[a-z0-9' -]+$/.test(w)), generated: true })
      console.log(`${generated.length}/${candidates.length} ${id}: ${size.join(' x ')} m`)
      await writeLock(lock)
    } catch (error) {
      console.log(`skip ${id}: ${(error as Error).message}`)
    }
  }
  const lines = generated.map((a) => `  ${JSON.stringify(a)},`)
  await writeFile(new URL('../src/core/generated-assets.ts', import.meta.url), `// Generated by scripts/grow-library.ts from Poly Haven's CC0 model library;\n// do not edit by hand. Sizes are measured from each glTF.\nimport type { AssetInfo } from './assets.ts'\n\nexport const GENERATED_ASSETS: AssetInfo[] = [\n${lines.join('\n')}\n]\n`)
  console.log(`wrote ${generated.length} assets`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
